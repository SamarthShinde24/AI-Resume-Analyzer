/**
 * Generates an interview-prep and ATS audit report formatted as GitHub-flavored Markdown.
 *
 * @param {Object} result - Analysis result object from /api/analyze
 * @param {Object} meta - Optional metadata (fileName, roleTitle, candidateName, date)
 * @returns {string} Markdown text
 */
export function generateMarkdownReport(result, meta = {}) {
  const dateStr = meta.date || new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  const fileName = meta.fileName || "Uploaded Resume";
  const roleTitle = meta.roleTitle || "Target Role";
  const score = result.match_score ?? 0;
  const breakdown = result.score_breakdown || {};

  const getVerdictLabel = (val) => {
    if (val >= 85) return "Exceptional Alignment (Top 10% Candidate)";
    if (val >= 70) return "Strong Candidate (Ready for Interview)";
    if (val >= 50) return "Moderate Fit (Requires Targeted Tailoring)";
    return "High Risk (Critical Requirement Gaps)";
  };

  const matchedSkills = result.matched_skills || [];
  const missingSkills = result.missing_skills || [];
  const checklist = result.keyword_checklist || [];
  const weakBullets = result.weak_bullets || [];

  return `# ATS Resume & Interview-Prep Audit Sheet

> **Generated on:** ${dateStr}  
> **Resume Document:** \`${fileName}\`  
> **Target Position:** ${roleTitle}  
> **Overall ATS Alignment Score:** **${score} / 100** — *${getVerdictLabel(score)}*

---

## 1. Executive Summary & Verdict

${result.summary || "No summary provided."}

---

## 2. Multi-Dimensional ATS Score Breakdown

| Evaluation Dimension | Score | Weight | Assessment |
| :--- | :---: | :---: | :--- |
| **Hard Skills Alignment** | **${breakdown.skills_match ?? score}%** | 35% | Direct match of required tech stack and tooling. |
| **Experience & Seniority Fit** | **${breakdown.experience_fit ?? score}%** | 30% | Years of tenure, domain complexity, and leadership scope. |
| **Quantifiable Impact** | **${breakdown.quantifiable_impact ?? Math.max(30, score - 10)}%** | 20% | Presence of metrics, %, $, throughput scale, and business outcomes. |
| **ATS Readability & Formatting** | **${breakdown.ats_readability ?? 85}%** | 15% | Standard heading conventions, machine parseability, and clean layout. |

---

## 3. Keyword & Competency Gap Analysis

### ✅ Matched Competencies (${matchedSkills.length})
${
  matchedSkills.length > 0
    ? matchedSkills.map((s) => `- \`${s}\``).join("\n")
    : "*No direct keyword matches identified.*"
}

### ⚠️ Priority Keyword Gaps & Placement Tips
${
  checklist.length > 0
    ? checklist
        .filter((item) => item.status === "missing")
        .map(
          (item) =>
            `- **${item.skill}** [${item.type === "required" ? "Required Must-Have" : "Nice-to-Have"}]\n  - *Placement Tip:* ${item.tip}`
        )
        .join("\n\n")
    : missingSkills.length > 0
    ? missingSkills.map((s) => `- **${s}** [Required]: Add to your technical summary and reference hands-on in a project bullet.`).join("\n")
    : "*All target keywords from the job description are matched!*"
}

---

## 4. Suggested Bullet Point Rewrites

${
  weakBullets.length > 0
    ? weakBullets
        .map(
          (b, idx) => `### Bullet ${idx + 1}
- **Original Phrasing:** ~${b.original}~
- **Recruiter Issue:** *${b.issue}*
- **Optimized Rewrite:**
  > ${b.rewrite}
`
        )
        .join("\n")
    : "*No weak bullet points flagged for revision.*"
}

---

## 5. Candidate Pre-Interview Checklist

- [ ] Incorporate missing core required keywords naturally into your technical skills summary.
- [ ] Update flagged bullet points with quantified scale, metrics, or dollar impact.
- [ ] Review the matched competencies above to prepare specific STAR interview talking points.
- [ ] Export your tailored resume as a clean PDF before submitting to the company portal.

---
*Report generated by AI Resume Analyzer Engine • ATS Evaluation System*
`;
}

/**
 * Triggers an immediate browser file download for text/markdown blobs.
 */
export function downloadFile(content, filename, type = "text/markdown;charset=utf-8;") {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
